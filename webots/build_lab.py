"""Builds the Raqib build lab: an empty test room where you assemble the robot yourself, step by step.

    python webots/build_lab.py

Writes two worlds next to the campus:
  worlds/raqib_build_lab.wbt           the empty lab (start here, follow the build guide)
  worlds/raqib_build_lab_solution.wbt  the same lab with the finished robot (compare if you get stuck)

The finished robot is assembled from webots/build_steps/*.wbt, the exact snippets the guide tells you to paste.
"""
from __future__ import annotations

from pathlib import Path

from PIL import ImageDraw

from build_world import ROOT, TEX, app, box, cyl, f, font, look_rotation, office_chair, texture

STEPS = ROOT / "build_steps"
MARK = "    # >>> paste the next step's parts here <<<"


def make_lab_textures():
    def grid(d: ImageDraw.ImageDraw, w, h):
        # 1 px = 0.5 cm; minor line every 10 cm, major every 50 cm, numbers every metre
        for i in range(0, w + 1, 20):
            major = i % 100 == 0
            d.line([(i, 0), (i, h)], fill=(150, 156, 170) if major else (196, 200, 210), width=3 if major else 1)
        for j in range(0, h + 1, 20):
            major = j % 100 == 0
            d.line([(0, j), (w, j)], fill=(150, 156, 170) if major else (196, 200, 210), width=3 if major else 1)
    texture("lab_floor.png", 1200, 800, (226, 229, 236), [], extra=grid)

    def card(d: ImageDraw.ImageDraw, w, h):
        d.rectangle([20, 20, w - 20, h - 20], outline=(13, 21, 48), width=10)
        for k, c in enumerate([(255, 107, 107), (255, 169, 77), (255, 212, 59), (61, 213, 152), (61, 99, 255), (124, 149, 255)]):
            d.rectangle([60 + k * 150, h - 190, 60 + k * 150 + 130, h - 70], fill=c)
        cy = h // 2
        d.ellipse([w // 2 - 50, cy - 50, w // 2 + 50, cy + 50], outline=(13, 21, 48), width=8)
        d.line([(w // 2, cy - 80), (w // 2, cy + 80)], fill=(13, 21, 48), width=6)
        d.line([(w // 2 - 80, cy), (w // 2 + 80, cy)], fill=(13, 21, 48), width=6)
        fnt = font(52)
        for k, line in enumerate(["RAQIB CAMERA TEST", "the cross should be in the middle"]):
            tw = d.textlength(line, font=fnt)
            d.text(((w - tw) / 2, 60 + k * 66), line, fill=(13, 21, 48), font=fnt)
    texture("lab_testcard.png", 1000, 700, (250, 250, 252), [], extra=card)


def lab_nodes() -> list[str]:
    W, D, H = 6.0, 4.0, 1.2
    nodes = [
        # floor with a 10 cm grid (lines every 10 cm, bold every 50 cm): measure how far the robot drives
        f'Solid {{ translation 1 0 -0.01 name "lab floor" children [ Shape {{ appearance {app((1, 1, 1), rough=0.9, tex="lab_floor.png")} '
        f'geometry Box {{ size {W} {D} 0.02 }} }} ] boundingObject Box {{ size {W} {D} 0.02 }} }}',
    ]
    for name, pos, size in [("north wall", (1, D / 2, H / 2), (W, 0.05, H)), ("south wall", (1, -D / 2, H / 2), (W, 0.05, H)),
                            ("east wall", (1 + W / 2, 0, H / 2), (0.05, D, H)), ("west wall", (1 - W / 2, 0, H / 2), (0.05, D, H))]:
        nodes.append(f'Solid {{ translation {f(pos)} name "{name}" children [ Shape {{ appearance {app((0.86, 0.88, 0.92))} '
                     f'geometry Box {{ size {f(size)} }} }} ] boundingObject Box {{ size {f(size)} }} }}')
    # test card on the east wall, centre at camera height (1.05 m) straight ahead of the start point
    nodes.append(f'Solid {{ translation {1 + W / 2 - 0.03} 0 1.05 rotation 0.5774 -0.5774 -0.5774 2.0944 name "camera test card" children [ '
                 f'Shape {{ appearance {app((1, 1, 1), rough=0.6, tex="lab_testcard.png")} '
                 f'geometry Plane {{ size 1.0 0.7 }} }} ] }}')
    # cardboard box 1.5 m ahead: the centre ultrasonic sensor should read about 140 cm from the start
    nodes.append(f'Solid {{ translation 1.6 0 0.15 name "cardboard box" children [ Shape {{ appearance {app((0.72, 0.55, 0.36))} '
                 f'geometry Box {{ size 0.2 0.4 0.3 }} }} ] boundingObject Box {{ size 0.2 0.4 0.3 }} }}')
    nodes.append(office_chair("chair", (1.3, 1.25, 0), rot=-2.2))
    # start mark
    nodes.append(f'Pose {{ translation 0 0 0.001 children [ Shape {{ appearance {app((0.24, 0.39, 1.0), emissive=(0.05, 0.1, 0.3))} '
                 f'geometry Cylinder {{ height 0.001 radius 0.03 }} }} ] }}')
    return nodes


def header(title: str, info: str) -> str:
    vp_pos, vp_target = (-1.4, -1.6, 1.2), (0.2, 0.0, 0.25)
    return f"""#VRML_SIM R2025a utf8
# {title} - generated by webots/build_lab.py. Follow the Raqib build guide.

WorldInfo {{
  info [ "{info}" ]
  title "{title}"
  basicTimeStep 16
  contactProperties [ ContactProperties {{ material2 "caster" coulombFriction [ 0.02 ] }} ]
}}
Viewpoint {{
  orientation {f(look_rotation(vp_pos, vp_target))}
  position {f(vp_pos)}
  fieldOfView 0.9
  near 0.02
}}
Background {{ skyColor [ 0.78 0.82 0.88 ] luminosity 0.3 }}
DirectionalLight {{ direction 0.3 0.5 -1 intensity 0.25 castShadows TRUE }}
PointLight {{ location 1 0 2.6 intensity 1.6 radius 8 castShadows FALSE }}
"""


def assembled_robot() -> str:
    """Step 2 is the Robot itself; every later step is pasted at the marker inside its children."""
    files = sorted(STEPS.glob("step*.wbt"))
    robot = files[0].read_text(encoding="utf-8")
    for p in files[1:]:
        part = p.read_text(encoding="utf-8").rstrip() + "\n"
        robot = robot.replace(MARK, part + MARK)
    return robot


def build():
    make_lab_textures()
    nodes = "\n".join(lab_nodes())
    lab = header("Raqib build lab", "Empty lab: build Raqib here step by step") + nodes + "\n"
    out = ROOT / "worlds" / "raqib_build_lab.wbt"
    out.write_text(lab, encoding="utf-8", newline="\n")
    sol = header("Raqib build lab (solution)", "The finished robot, built from the guide's steps") + nodes + "\n" + assembled_robot()
    (ROOT / "worlds" / "raqib_build_lab_solution.wbt").write_text(sol, encoding="utf-8", newline="\n")
    print(f"Wrote {out.name} and raqib_build_lab_solution.wbt")


if __name__ == "__main__":
    build()
